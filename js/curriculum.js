export const termsOf = (subject) => Object.keys(CURRICULUM[subject] || {});

// 프로필 학년(예: "중2")과 오늘 날짜로 지금 배우는 학기를 고른다 (3~8월 1학기, 9~2월 2학기)
export function currentTerm(subject, grade) {
  const terms = termsOf(subject);
  if (!grade) return terms[0];
  const month = new Date().getMonth() + 1;
  const sem = month >= 3 && month <= 8 ? 1 : 2;
  const exact = `${grade}-${sem}`;
  if (terms.includes(exact)) return exact;
  // 사회(중학)·고2·3처럼 학기로 나누지 않는 경우
  const level = grade[0], year = grade.slice(1);
  if (subject === "social" && level === "중") return terms.find((t) => t.startsWith("중")) || terms[0];
  return terms.find((t) => t.startsWith(grade)) || terms.find((t) => t.startsWith(level) && t.includes(year)) || terms.find((t) => t.startsWith(level)) || terms[0];
}

// 단원 이름이 어느 학년-학기 목록에 있는지 (보여 줄 때 "중1-1 · 일차방정식")
export function termOfChapter(subject, chapter) {
  for (const [t, list] of Object.entries(CURRICULUM[subject] || {})) if (list.includes(chapter)) return t;
  return null;
}
