const rand = (min, max) => Math.floor(Math.random() * (max - min + 1)) + min;
const randNZ = (min, max) => { let v = 0; while (v === 0) v = rand(min, max); return v; };
const gcd = (a, b) => (b === 0 ? Math.abs(a) : gcd(b, a % b));
export function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

// 정답 + 오답 후보들로 보기 4개를 만든다 (중복 제거, 부족하면 근처 값으로 채움)
function mc(correct, wrongs, fill) {
  const set = [String(correct)];
  for (const w of wrongs) { const s = String(w); if (!set.includes(s) && set.length < 4) set.push(s); }
  let k = 1;
  while (set.length < 4) { const s = String(fill(k++)); if (!set.includes(s)) set.push(s); }
  const c = shuffle(set);
  return { c, a: c.indexOf(String(correct)) };
}
const frac = (n, d) => { const g = gcd(n, d); n /= g; d /= g; return d === 1 ? `${n}` : `${n}/${d}`; };
const sgn = (v) => (v < 0 ? `(${v})` : `${v}`);
// ax + b 꼴 식을 보기 좋게
function lin(a, b) {
  let s = a === 1 ? "x" : a === -1 ? "-x" : `${a}x`;
  if (b > 0) s += ` + ${b}`; else if (b < 0) s += ` - ${-b}`;
  return s;
}

