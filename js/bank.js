// 공용 형식으로 바꿔 줌: { question, choices, answer, explanation }
const norm = (p) => ({ question: p.q, choices: p.c, answer: p.a, explanation: p.e });

export function unitsFor(subject, customUnits = []) {
  return [...BANK, ...customUnits].filter((u) => u.subject === subject);
}
export function findUnit(id, customUnits = []) {
  return [...BANK, ...customUnits].find((u) => u.id === id) || null;
}

// 단원에서 문제 n개를 뽑는다. 이미 낸 문제(seen)는 되도록 피한다.
export function drawProblems(unit, n = 3, seen = []) {
  if (unit.gen) {
    const out = [];
    for (let tries = 0; out.length < n && tries < 50; tries++) {
      const p = unit.gen();
      if (!out.some((o) => o.q === p.q) && !seen.includes(p.q)) out.push(p);
    }
    return out.map(norm);
  }
  const pool = unit.p || [];
  let fresh = shuffle(pool.filter((p) => !seen.includes(p.q)));
  if (fresh.length < n) fresh = [...fresh, ...shuffle(pool.filter((p) => !fresh.includes(p)))];
  // 보기 순서도 섞어서 같은 문제라도 위치를 외우지 않게
  return fresh.slice(0, n).map((p) => {
    const order = shuffle(p.c.map((_, i) => i));
    return { question: p.q, choices: order.map((i) => p.c[i]), answer: order.indexOf(p.a), explanation: p.e };
  });
}
